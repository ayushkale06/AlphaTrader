"""Export deterministic JSON Schemas and human-readable Kafka contract documentation.

Usage::

    python -m scripts.export_schemas
    python -m scripts.export_schemas --check
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path

from src.common.contracts import (
    TOPIC_REGISTRY,
    TopicName,
    build_sample_topic_messages,
    validate_topic_message,
)
from src.common.schemas import (
    AlphaTraderBaseModel,
    Candle,
    Fill,
    HaltEvent,
    MarketStatus,
    Order,
    OrderRequest,
    PortfolioSnapshot,
    Position,
    QuantSignal,
    RiskDecision,
    RiskInputSnapshot,
    SystemEvent,
    TechnicalSignal,
    Tick,
)

REPO_ROOT = Path(__file__).resolve().parent.parent
CONTRACTS_DIR = REPO_ROOT / "docs" / "contracts"
CONTRACTS_DOC_PATH = REPO_ROOT / "docs" / "contracts.md"

EXPORTED_MODELS: dict[str, type[AlphaTraderBaseModel]] = {
    "Tick": Tick,
    "Candle": Candle,
    "MarketStatus": MarketStatus,
    "TechnicalSignal": TechnicalSignal,
    "QuantSignal": QuantSignal,
    "RiskInputSnapshot": RiskInputSnapshot,
    "RiskDecision": RiskDecision,
    "HaltEvent": HaltEvent,
    "OrderRequest": OrderRequest,
    "Order": Order,
    "Fill": Fill,
    "Position": Position,
    "PortfolioSnapshot": PortfolioSnapshot,
    "SystemEvent": SystemEvent,
    "EventEnvelope_Tick": TOPIC_REGISTRY[TopicName.MARKET_TICKS].envelope_model,
    "EventEnvelope_Candle": TOPIC_REGISTRY[TopicName.MARKET_CANDLES].envelope_model,
    "EventEnvelope_TechnicalSignal": TOPIC_REGISTRY[TopicName.SIGNALS_TECHNICAL].envelope_model,
    "EventEnvelope_QuantSignal": TOPIC_REGISTRY[TopicName.SIGNALS_QUANT].envelope_model,
    "EventEnvelope_RiskDecision": TOPIC_REGISTRY[TopicName.RISK_DECISIONS].envelope_model,
    "EventEnvelope_OrderRequest": TOPIC_REGISTRY[TopicName.ORDERS_REQUESTS].envelope_model,
    "EventEnvelope_Fill": TOPIC_REGISTRY[TopicName.ORDERS_FILLS].envelope_model,
    "EventEnvelope_PortfolioSnapshot": TOPIC_REGISTRY[TopicName.PORTFOLIO_UPDATES].envelope_model,
    "EventEnvelope_SystemEvent": TOPIC_REGISTRY[TopicName.SYSTEM_EVENTS].envelope_model,
}


def render_model_schema_json(model_cls: type[AlphaTraderBaseModel]) -> str:
    """Render a deterministic, sorted JSON Schema string for a Pydantic v2 model."""
    schema_dict = model_cls.model_json_schema()
    return json.dumps(schema_dict, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_contracts_markdown() -> str:
    """Render docs/contracts.md using live TOPIC_REGISTRY metadata and real model instances."""
    sample_messages = build_sample_topic_messages()

    lines: list[str] = [
        "# AlphaTrader Event & Schema Contract Specification",
        "",
        (
            "> **Auto-Generated & Verified Artifact:** Generated by "
            "[`scripts/export_schemas.py`](../scripts/export_schemas.py) from "
            "[`src/common/contracts.py`](../src/common/contracts.py) and "
            "[`src/common/schemas/`](../src/common/schemas/).  "
        ),
        (
            "> **CI Enforcement:** `make schemas` exports these contracts; `make check` "
            "runs `python -m scripts.export_schemas --check` and fails if any JSON Schema "
            "or sample payload is out of date."
        ),
        "",
        "---",
        "",
        "## 1. Core Contract Invariants",
        "",
        (
            "1. **No Untyped Dicts**: Every message published to Redpanda/Kafka or exchanged "
            "between MCP servers and LangGraph agents is wrapped in `EventEnvelope[T]` and "
            "validated via Pydantic v2 (`frozen=True`, `extra='forbid'`)."
        ),
        (
            "2. **Exact Decimal Financial Math**: All prices, quantities, notional values, "
            "fees, and PnL figures use `decimal.Decimal` serialized as plain strings in JSON. "
            "Binary `float` inputs are rejected at validation time."
        ),
        (
            "3. **UTC-Aware Timestamps**: All timestamps (`timestamp`, `open_time`, "
            "`close_time`, `evaluated_at`, `requested_at`, `filled_at`, `produced_at`) "
            "reject naive `datetime` objects and normalize to UTC."
        ),
        (
            "4. **NSE Symbol Validation**: Ticker symbols are validated against NSE "
            "conventions (`^[A-Z][A-Z0-9&-]{1,14}(?:\\.NS)?$`)."
        ),
        "",
        "---",
        "",
        "## 2. Redpanda / Kafka Topic Contract Registry",
        "",
        (
            "| Topic | Payload Model | Partition Key Rule | Partitions | Retention (h) | "
            "DLQ Topic | Allowed Producers | Allowed Consumers |"
        ),
        "|---|---|---|---:|---:|---|---|---|",
    ]

    for topic_name in TopicName:
        contract = TOPIC_REGISTRY[topic_name]
        producers = ", ".join(f"`{p.value}`" for p in sorted(contract.allowed_producers))
        consumers = ", ".join(f"`{c.value}`" for c in sorted(contract.allowed_consumers))
        dlq_display = f"`{contract.dlq_topic}`" if contract.dlq_topic else "None"
        payload_name = contract.payload_model.__name__
        schema_link = f"[`{payload_name}`](contracts/{payload_name}.schema.json)"
        lines.append(
            f"| `{contract.topic.value}` | {schema_link} | `{contract.key_rule.value}` | "
            f"{contract.partitions} | {contract.retention_hours} | {dlq_display} | "
            f"{producers} | {consumers} |"
        )

    lines.extend(
        [
            "",
            "---",
            "",
            "## 3. Exported JSON Schema Index",
            "",
            "| Model / Envelope | JSON Schema Artifact |",
            "|---|---|",
        ]
    )

    for name in EXPORTED_MODELS:
        lines.append(
            f"| `{name}` | [`docs/contracts/{name}.schema.json`](contracts/{name}.schema.json) |"
        )

    lines.extend(
        [
            "",
            "---",
            "",
            "## 4. Validated Sample Kafka Messages (Generated from Real Model Instances)",
            "",
        ]
    )

    for idx, topic_name in enumerate(TopicName, start=1):
        contract = TOPIC_REGISTRY[topic_name]
        envelope = sample_messages[topic_name]
        extracted_key = contract.extract_message_key(envelope)
        validate_topic_message(topic_name, envelope, message_key=extracted_key)

        pretty_json = json.dumps(
            json.loads(envelope.to_json_bytes().decode("utf-8")),
            indent=2,
            sort_keys=True,
            ensure_ascii=False,
        )
        p_name = contract.payload_model.__name__
        env_name = f"EventEnvelope_{p_name}"

        lines.extend(
            [
                f"### 4.{idx} `{contract.topic.value}`",
                "",
                f"- **Description:** {contract.description}",
                f"- **Payload Schema:** [`{p_name}.schema.json`](contracts/{p_name}.schema.json)",
                (
                    f"- **Envelope Schema:** [`{env_name}.schema.json`]"
                    f"(contracts/{env_name}.schema.json)"
                ),
                f"- **Partition Key (`{contract.key_rule.value}`):** `{extracted_key}`",
                "",
                "```json",
                pretty_json,
                "```",
                "",
            ]
        )

    return "\n".join(lines)


def export_all_schemas(
    contracts_dir: Path = CONTRACTS_DIR,
    contracts_doc_path: Path = CONTRACTS_DOC_PATH,
    *,
    check_only: bool = False,
) -> int:
    """Write or verify all JSON Schema files and docs/contracts.md."""
    stale_or_missing: list[str] = []

    if not check_only:
        contracts_dir.mkdir(parents=True, exist_ok=True)

    expected_filenames: set[str] = set()
    for model_name, model_cls in EXPORTED_MODELS.items():
        filename = f"{model_name}.schema.json"
        expected_filenames.add(filename)
        target_path = contracts_dir / filename
        rendered = render_model_schema_json(model_cls)

        if check_only:
            if not target_path.exists():
                stale_or_missing.append(f"Missing schema file: {target_path}")
            elif target_path.read_text(encoding="utf-8") != rendered:
                stale_or_missing.append(f"Out-of-date schema file: {target_path}")
        else:
            target_path.write_text(rendered, encoding="utf-8", newline="\n")

    if contracts_dir.exists():
        for existing in sorted(contracts_dir.glob("*.schema.json")):
            if existing.name not in expected_filenames:
                if check_only:
                    stale_or_missing.append(f"Unexpected extra schema file: {existing}")
                else:
                    existing.unlink()

    rendered_doc = render_contracts_markdown()
    if check_only:
        if not contracts_doc_path.exists():
            stale_or_missing.append(f"Missing contract guide: {contracts_doc_path}")
        elif contracts_doc_path.read_text(encoding="utf-8") != rendered_doc:
            stale_or_missing.append(f"Out-of-date contract guide: {contracts_doc_path}")
    else:
        contracts_doc_path.parent.mkdir(parents=True, exist_ok=True)
        contracts_doc_path.write_text(rendered_doc, encoding="utf-8", newline="\n")

    rel_dir = contracts_dir.relative_to(REPO_ROOT)
    rel_doc = contracts_doc_path.relative_to(REPO_ROOT)
    if check_only:
        if stale_or_missing:
            for item in stale_or_missing:
                print(f"ERROR: {item}", file=sys.stderr)
            print(
                "Run `make schemas` (or `python -m scripts.export_schemas`) to regenerate.",
                file=sys.stderr,
            )
            return 1
        print(
            f"Verified {len(EXPORTED_MODELS)} JSON Schemas in {rel_dir} "
            f"and {rel_doc} are up to date."
        )
        return 0

    print(f"Exported {len(EXPORTED_MODELS)} JSON Schemas to {rel_dir} and generated {rel_doc}.")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entry point for exporting or checking JSON Schemas and contract docs."""
    parser = argparse.ArgumentParser(
        description="Export or verify AlphaTrader Pydantic v2 JSON Schemas and contract docs.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that committed JSON Schemas and docs/contracts.md are up to date.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)
    return export_all_schemas(check_only=bool(args.check))


if __name__ == "__main__":
    raise SystemExit(main())
