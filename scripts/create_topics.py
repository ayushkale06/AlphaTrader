"""Kafka/Redpanda topic provisioning script driven directly by TOPIC_REGISTRY.

Single source of truth: reads ``TOPIC_REGISTRY`` from ``src.common.contracts``
and idempotently creates every registered topic with its configured partition count,
retention period, and dead-letter queue (.dlq) where specified.

Supports:
1. Native Python provisioning via ``confluent-kafka`` AdminClient.
2. Generating a self-contained shell script (``init_topics.sh``) for the
   ``redpanda-init`` Docker Compose container using ``rpk``.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from src.common.contracts import TOPIC_REGISTRY

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INIT_SH_PATH = REPO_ROOT / "deploy" / "docker" / "init_topics.sh"


def compute_topic_specifications() -> list[dict[str, Any]]:
    """Derive topic definitions (primary + dlq) directly from TOPIC_REGISTRY."""
    specs: list[dict[str, Any]] = []
    for topic_name, contract in TOPIC_REGISTRY.items():
        retention_ms = contract.retention_hours * 3600 * 1000
        specs.append(
            {
                "topic": topic_name.value,
                "partitions": contract.partitions,
                "replication_factor": 1,
                "retention_ms": retention_ms,
                "is_dlq": False,
                "description": contract.description,
            }
        )
        if contract.needs_dlq and contract.dlq_topic:
            specs.append(
                {
                    "topic": contract.dlq_topic,
                    "partitions": max(1, contract.partitions // 2),
                    "replication_factor": 1,
                    "retention_ms": retention_ms,
                    "is_dlq": True,
                    "description": f"Dead-letter queue for {topic_name.value}.",
                }
            )
    return specs


def generate_rpk_init_script_content(broker: str = "redpanda:9092") -> str:
    """Generate a POSIX shell script using rpk to create all topics idempotently."""
    specs = compute_topic_specifications()
    lines: list[str] = [
        "#!/bin/sh",
        "# =============================================================================",
        "# Auto-generated by scripts/create_topics.py from src/common/contracts.py",
        "# DO NOT EDIT DIRECTLY. Run `python -m scripts.create_topics --generate-init-script`.",
        "# =============================================================================",
        "set -e",
        "",
        f'BROKER="${{REDPANDA_BROKER:-{broker}}}"',
        'ADMIN_API="${REDPANDA_ADMIN_API:-redpanda:9644}"',
        'echo "Waiting for Redpanda cluster health at ${ADMIN_API}..."',
        'until rpk cluster health --api-urls "${ADMIN_API}" >/dev/null 2>&1; do',
        '    echo "Redpanda not ready yet, sleeping 2s..."',
        "    sleep 2",
        "done",
        'echo "Redpanda cluster is healthy. Provisioning topics from TOPIC_REGISTRY..."',
        "",
    ]

    for spec in specs:
        topic = spec["topic"]
        partitions = spec["partitions"]
        retention_ms = spec["retention_ms"]
        desc = spec["description"]
        lines.append(f"# {desc}")
        lines.append(
            f'rpk topic create "{topic}" --brokers "${{BROKER}}" '
            f"-p {partitions} -r 1 -c retention.ms={retention_ms} || true"
        )
        lines.append("")

    lines.append('echo "All topics from TOPIC_REGISTRY provisioned successfully."')
    lines.append('rpk topic list --brokers "${BROKER}"')
    lines.append("")
    return "\n".join(lines)


def write_rpk_init_script(target_path: Path = DEFAULT_INIT_SH_PATH) -> Path:
    """Write the rpk initialization script to target_path with LF line endings."""
    content = generate_rpk_init_script_content()
    target_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.write_text(content, encoding="utf-8", newline="\n")
    return target_path


def provision_topics_via_admin_client(
    bootstrap_servers: str = "127.0.0.1:9092",
    *,
    dry_run: bool = False,
    timeout_seconds: float = 20.0,
) -> int:
    """Create all contract topics via confluent_kafka AdminClient."""
    from confluent_kafka import KafkaError
    from confluent_kafka.admin import (  # type: ignore[attr-defined]
        AdminClient,
        NewTopic,
    )

    specs = compute_topic_specifications()
    print(f"Connecting to Kafka/Redpanda at {bootstrap_servers}...")
    admin = AdminClient({"bootstrap.servers": bootstrap_servers, "client.id": "alphatrader-init"})

    # Check cluster metadata
    try:
        cluster_metadata = admin.list_topics(timeout=timeout_seconds)
        existing_topics = set(cluster_metadata.topics.keys())
        print(f"Connected to cluster. Existing topics count: {len(existing_topics)}")
    except Exception as exc:
        print(f"ERROR: Failed to connect to Kafka at {bootstrap_servers}: {exc}", file=sys.stderr)
        return 1

    new_topics: list[NewTopic] = []
    skipped_count = 0

    for spec in specs:
        topic_name = spec["topic"]
        if topic_name in existing_topics:
            print(f"  [EXISTS] {topic_name} (skipping)")
            skipped_count += 1
            continue

        print(
            f"  [CREATE] {topic_name} (partitions={spec['partitions']}, "
            f"retention.ms={spec['retention_ms']})"
        )
        new_topics.append(
            NewTopic(
                topic=topic_name,
                num_partitions=spec["partitions"],
                replication_factor=spec["replication_factor"],
                config={"retention.ms": str(spec["retention_ms"])},
            )
        )

    if dry_run:
        print(f"Dry run complete: {len(new_topics)} topics to create, {skipped_count} existing.")
        return 0

    if not new_topics:
        print(f"All {len(specs)} topics already exist. Nothing to create.")
        return 0

    futures = admin.create_topics(new_topics, request_timeout=timeout_seconds)
    has_errors = False
    for topic, future in futures.items():
        try:
            future.result()
            print(f"  [OK] Created topic: {topic}")
        except Exception as exc:
            # Kafka error code 36 is TOPIC_ALREADY_EXISTS
            err_code = None
            if hasattr(exc, "args") and exc.args:
                arg0 = exc.args[0]
                if hasattr(arg0, "code") and callable(arg0.code):
                    err_code = arg0.code()
                elif hasattr(arg0, "code"):
                    err_code = arg0.code

            if err_code == KafkaError.TOPIC_ALREADY_EXISTS:
                print(f"  [EXISTS] Topic {topic} already exists (skipping).")
            else:
                print(f"  [ERROR] Failed to create {topic}: {exc}", file=sys.stderr)
                has_errors = True

    if has_errors:
        return 1

    print(f"Successfully ensured all {len(specs)} topics from TOPIC_REGISTRY.")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entry point for topic creation and init script generation."""
    parser = argparse.ArgumentParser(
        description="Provision AlphaTrader Kafka/Redpanda topics from TOPIC_REGISTRY.",
    )
    parser.add_argument(
        "--bootstrap-servers",
        default="127.0.0.1:9092",
        help="Kafka bootstrap servers (default: 127.0.0.1:9092).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="List topics that would be created without making changes.",
    )
    parser.add_argument(
        "--generate-init-script",
        action="store_true",
        help="Generate deploy/docker/init_topics.sh from TOPIC_REGISTRY.",
    )
    parser.add_argument(
        "--init-script-path",
        type=Path,
        default=DEFAULT_INIT_SH_PATH,
        help="Target path for generated init_topics.sh script.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.generate_init_script:
        target = write_rpk_init_script(args.init_script_path)
        print(f"Generated {target} directly from TOPIC_REGISTRY.")
        return 0

    return provision_topics_via_admin_client(
        bootstrap_servers=args.bootstrap_servers,
        dry_run=args.dry_run,
    )


if __name__ == "__main__":
    raise SystemExit(main())
