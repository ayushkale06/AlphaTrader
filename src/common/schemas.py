"""
AlphaTrader Common Data Schemas
Pydantic v2 Models for Market Data, Technical Indicators, Trade Proposals, Risk Evaluations, and Execution Orders.
"""

from enum import Enum
from datetime import datetime
from typing import Optional, List, Dict
from pydantic import BaseModel, Field, field_validator, ConfigDict


class SignalAction(str, Enum):
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"


class RiskDecision(str, Enum):
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    CIRCUIT_BREAKER_HALT = "CIRCUIT_BREAKER_HALT"


class OrderStatus(str, Enum):
    PENDING = "PENDING"
    FILLED = "FILLED"
    PARTIALLY_FILLED = "PARTIALLY_FILLED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"


class MarketTick(BaseModel):
    """Raw tick data frame received from NSE market data feed."""
    model_config = ConfigDict(frozen=True)

    symbol: str = Field(..., description="Stock ticker symbol (e.g. NIFTY50_RELIANCE)")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="Tick arrival timestamp in UTC")
    bid_price: float = Field(..., gt=0, description="Top bid price")
    ask_price: float = Field(..., gt=0, description="Top ask price")
    last_price: float = Field(..., gt=0, description="Last traded price")
    volume: int = Field(..., ge=0, description="Cumulative volume for current session")
    vwap: Optional[float] = Field(None, gt=0, description="Volume Weighted Average Price")

    @field_validator('ask_price')
    @classmethod
    def validate_ask_higher_or_equal_bid(cls, ask: float, info) -> float:
        bid = info.data.get('bid_price')
        if bid is not None and ask < bid:
            raise ValueError(f"Ask price ({ask}) cannot be less than bid price ({bid})")
        return ask


class TechnicalIndicators(BaseModel):
    """Calculated technical indicators over dynamic windows."""
    symbol: str = Field(..., description="Stock ticker symbol")
    timestamp: datetime = Field(default_factory=datetime.utcnow)
    ema_20: float = Field(..., gt=0)
    ema_50: float = Field(..., gt=0)
    ema_200: float = Field(..., gt=0)
    rsi_14: float = Field(..., ge=0, le=100, description="RSI bounded between 0 and 100")
    macd_line: float
    macd_signal: float
    macd_hist: float
    bband_upper: float = Field(..., gt=0)
    bband_lower: float = Field(..., gt=0)
    vwap: float = Field(..., gt=0)


class OrderProposal(BaseModel):
    """Signal proposal generated by Quant Strategy Agent."""
    proposal_id: str = Field(..., description="Unique UUID for signal proposal")
    symbol: str = Field(..., description="Stock ticker symbol")
    action: SignalAction = Field(..., description="BUY, SELL, or HOLD")
    quantity: int = Field(..., gt=0, description="Number of shares requested")
    target_price: float = Field(..., gt=0, description="Desired execution price")
    stop_loss_price: float = Field(..., gt=0, description="Stop loss price limit")
    confidence_score: float = Field(..., ge=0.0, le=1.0, description="Agent confidence score (0.0 to 1.0)")
    strategy_name: str = Field(..., description="Originating quantitative strategy name")
    timestamp: datetime = Field(default_factory=datetime.utcnow)

    @field_validator('stop_loss_price')
    @classmethod
    def validate_stop_loss(cls, stop_loss: float, info) -> float:
        action = info.data.get('action')
        target = info.data.get('target_price')
        if action == SignalAction.BUY and target is not None and stop_loss >= target:
            raise ValueError(f"Stop loss ({stop_loss}) for BUY order must be below target price ({target})")
        if action == SignalAction.SELL and target is not None and stop_loss <= target:
            raise ValueError(f"Stop loss ({stop_loss}) for SELL order must be above target price ({target})")
        return stop_loss


class RiskEvaluation(BaseModel):
    """Deterministic evaluation decision from Risk Guardrail microservice."""
    proposal_id: str = Field(..., description="ID of the evaluated proposal")
    symbol: str = Field(..., description="Stock ticker symbol")
    decision: RiskDecision = Field(..., description="APPROVED, REJECTED, or CIRCUIT_BREAKER_HALT")
    drawdown_check_passed: bool = Field(...)
    position_limit_check_passed: bool = Field(...)
    slippage_check_passed: bool = Field(...)
    current_daily_drawdown_pct: float = Field(..., description="Current account drawdown percentage")
    rejection_reason: Optional[str] = Field(None, description="Detailed failure rationale if rejected")
    evaluated_at: datetime = Field(default_factory=datetime.utcnow)


class ExecutedOrder(BaseModel):
    """Execution receipt from Broker API microservice."""
    order_id: str = Field(..., description="Unique execution order ID")
    proposal_id: str = Field(..., description="Associated proposal ID")
    symbol: str = Field(..., description="Stock ticker symbol")
    action: SignalAction
    executed_quantity: int = Field(..., gt=0)
    executed_price: float = Field(..., gt=0)
    slippage: float = Field(..., description="Price slippage experienced during order fill")
    status: OrderStatus = Field(default=OrderStatus.FILLED)
    executed_at: datetime = Field(default_factory=datetime.utcnow)


class Position(BaseModel):
    """Active portfolio holding position."""
    symbol: str
    quantity: int = Field(..., ge=0)
    average_entry_price: float = Field(..., gt=0)
    current_market_price: float = Field(..., gt=0)
    unrealized_pnl: float
    realized_pnl: float


class PortfolioState(BaseModel):
    """Complete portfolio balance and risk metric state snapshot."""
    cash_balance: float = Field(..., ge=0)
    equity_value: float = Field(..., ge=0)
    total_portfolio_value: float = Field(..., gt=0)
    daily_realized_pnl: float
    daily_unrealized_pnl: float
    daily_drawdown_pct: float = Field(..., ge=0.0, le=100.0)
    active_positions: Dict[str, Position] = Field(default_factory=dict)
    updated_at: datetime = Field(default_factory=datetime.utcnow)
